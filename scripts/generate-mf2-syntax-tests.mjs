import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const pin = (
  await readFile(new URL("tests/unicode-mf2/PINNED_COMMIT", root), "utf8")
).trim();
assert.match(pin, /^[0-9a-f]{40}$/u);
const fixture = async name =>
  JSON.parse(
    await readFile(
      new URL(`tests/unicode-mf2/upstream/test/tests/${name}.json`, root),
      "utf8",
    ),
  );

const [syntax, syntaxErrors, dataModelErrors] = await Promise.all([
  fixture("syntax"),
  fixture("syntax-errors"),
  fixture("data-model-errors"),
]);

const moonString = value => {
  let result = '"';
  for (const char of value) {
    const code = char.codePointAt(0);
    if (char === '"') result += '\\"';
    else if (char === "\\") result += "\\\\";
    else if (char === "\n") result += "\\n";
    else if (char === "\r") result += "\\r";
    else if (char === "\t") result += "\\t";
    else if (code < 0x20 || code === 0x7f) result += `\\u{${code.toString(16)}}`;
    else result += char;
  }
  return result + '"';
};

const errorCodes = new Map([
  ["variant-key-mismatch", "Mf2VariantKeyMismatchCode"],
  ["missing-fallback-variant", "Mf2MissingFallbackVariantCode"],
  ["missing-selector-annotation", "Mf2MissingSelectorAnnotationCode"],
  ["duplicate-declaration", "Mf2DuplicateDeclarationCode"],
  ["duplicate-option-name", "Mf2DuplicateOptionNameCode"],
  ["duplicate-variant", "Mf2DuplicateVariantCode"],
]);

const syntaxSources = syntax.tests.map(test => test.src);
const invalidSyntaxSources = syntaxErrors.tests.map(test => test.src);
const modelCases = dataModelErrors.tests.map(test => ({
  source: test.src,
  codes: (test.expErrors ?? []).map(error => {
    assert.ok(errorCodes.has(error.type), `unmapped data-model error: ${error.type}`);
    return errorCodes.get(error.type);
  }),
}));

const source = `// Code generated by scripts/generate-mf2-syntax-tests.mjs; DO NOT EDIT.
// Unicode MessageFormat WG fixtures: ${pin}.

///|
test "Unicode MF2 pinned well-formed syntax fixtures" {
  let sources = [
${syntaxSources.map(value => `    ${moonString(value)},`).join("\n")}
  ]
  let failures : Array[String] = []
  for source in sources {
    match parse_mf2_syntax(source) {
      Ok(_) => ()
      Err(error) => failures.push(source + " => " + error.message)
    }
  }
  if !failures.is_empty() {
    fail("expected pinned well-formed syntax:\\n" + failures.join("\\n"))
  }
}

///|
test "Unicode MF2 pinned syntax-error fixtures" {
  let sources = [
${invalidSyntaxSources.map(value => `    ${moonString(value)},`).join("\n")}
  ]
  let failures : Array[String] = []
  for source in sources {
    match parse_mf2_syntax(source) {
      Err(error) if error.code == Mf2SyntaxCode => ()
      Err(error) => failures.push(source + " => wrong code " + error.message)
      Ok(_) => failures.push(source)
    }
  }
  if !failures.is_empty() {
    fail("expected pinned syntax errors:\\n" + failures.join("\\n"))
  }
}

///|
test "Unicode MF2 pinned data-model-error fixtures" {
${modelCases
  .map(({ source, codes }, index) => {
    if (codes.length === 0) {
      return `  guard parse_valid_mf2_model(${moonString(source)}) is Ok(_) else {\n    fail("expected valid pinned data model ${index}")\n  }`;
    }
    return `  let model_${index} = match parse_mf2_syntax(${moonString(source)}) {\n    Ok(value) => value\n    Err(error) => fail("expected well-formed pinned data model ${index}: " + error.message)\n  }\n  let errors_${index} = validate_mf2_model(model_${index})\n${codes.map(code => `  assert_true(errors_${index}.any(error => error.code == ${code}))`).join("\n")}`;
  })
  .join("\n")}
}
`;

const target = new URL("runtime/mf2_upstream_syntax_wbtest.mbt", root);
const format = path => {
  const result = spawnSync("moon", ["fmt", path], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`moon fmt failed:\n${result.stdout}${result.stderr}`);
  }
};
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  const candidate = join(
    fileURLToPath(new URL("runtime/", root)),
    `.mf2-generated-${process.pid}_wbtest.mbt`,
  );
  try {
    await writeFile(candidate, source);
    format(candidate);
    assert.equal(
      current,
      await readFile(candidate, "utf8"),
      "generated MF2 syntax tests are stale",
    );
  } finally {
    await rm(candidate, { force: true });
  }
  process.stdout.write(
    `MF2 generated tests current: ${syntaxSources.length} accepted, ${invalidSyntaxSources.length} rejected, ${modelCases.length} data-model cases\n`,
  );
} else {
  await writeFile(target, source);
  format(fileURLToPath(target));
  process.stdout.write(
    `Generated MF2 tests: ${syntaxSources.length} accepted, ${invalidSyntaxSources.length} rejected, ${modelCases.length} data-model cases\n`,
  );
}
