import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const pin = (
  await readFile(new URL("tests/unicode-mf2/PINNED_COMMIT", root), "utf8")
).trim();
assert.match(pin, /^[0-9a-f]{40}$/u);

const fixture = async name =>
  JSON.parse(
    await readFile(
      new URL(`tests/unicode-mf2/upstream/test/tests/${name}.json`, root),
      "utf8",
    ),
  );

const names = ["fallback", "pattern-selection", "bidi", "u-options"];
const files = await Promise.all(names.map(fixture));
const moonString = value => {
  let result = '"';
  for (const char of value) {
    const code = char.codePointAt(0);
    if (char === '"') result += '\\"';
    else if (char === "\\") result += "\\\\";
    else if (char === "\n") result += "\\n";
    else if (char === "\r") result += "\\r";
    else if (char === "\t") result += "\\t";
    else if (code < 0x20 || code === 0x7f) result += `\\u{${code.toString(16)}}`;
    else result += char;
  }
  return result + '"';
};

const errorCodes = new Map([
  ["syntax-error", "Mf2SyntaxCode"],
  ["bad-operand", "Mf2BadOperandCode"],
  ["bad-option", "Mf2BadOptionCode"],
  ["bad-selector", "Mf2BadSelectorCode"],
  ["bad-variant-key", "Mf2BadVariantKeyCode"],
  ["unknown-function", "Mf2UnknownFunctionCode"],
  ["unresolved-variable", "Mf2UnresolvedVariableCode"],
]);

const doubleLiteral = value => {
  assert.ok(Number.isFinite(value));
  if (Number.isInteger(value)) return `${value}.0`;
  return String(value);
};
const input = param => {
  const name = moonString(param.name);
  if (typeof param.value === "string") {
    return `Mf2Input::new(${name}, TextValue(${moonString(param.value)}))`;
  }
  if (typeof param.value === "number") {
    return `Mf2Input::new(${name}, DoubleValue(${doubleLiteral(param.value)}))`;
  }
  if (typeof param.value === "boolean") {
    return `Mf2Input::new(${name}, BoolValue(${param.value}))`;
  }
  throw new Error(`unsupported fixture input: ${JSON.stringify(param)}`);
};

const field = value => `mf2_fixture_field(${moonString(value)})`;
const partSignature = part => {
  switch (part.type) {
    case "text":
      return `"text|" + ${field(part.value)}`;
    case "bidiIsolation":
      return `"bidi|" + ${field(part.value)}`;
    case "fallback":
      return `"fallback|" + ${field(`{${part.source}}`)}`;
    case "string":
      return (
        `"expression|" + ${field("string")} + "|${part.dir ?? "unknown"}|" + ` +
        `${field(part.id ?? "")} + "|" + ${field(part.value)}`
      );
    case "markup":
      return (
        `"markup|${part.kind}|" + ${field(part.name)} + "|" + ` +
        field(part.id ?? "")
      );
    default:
      throw new Error(`unsupported expected part: ${JSON.stringify(part)}`);
  }
};

const cases = [];
for (let fileIndex = 0; fileIndex < files.length; fileIndex += 1) {
  const file = files[fileIndex];
  for (let testIndex = 0; testIndex < file.tests.length; testIndex += 1) {
    const test = file.tests[testIndex];
    const properties = { ...file.defaultTestProperties, ...test };
    const codes = (test.expErrors ?? []).map(error => {
      assert.ok(errorCodes.has(error.type), `unmapped formatting error: ${error.type}`);
      return errorCodes.get(error.type);
    });
    cases.push({
      label: `${names[fileIndex]} ${testIndex}: ${test.description ?? file.scenario}`,
      source: test.src,
      locale: properties.locale ?? "en-US",
      bidi:
        properties.bidiIsolation === "none"
          ? "Mf2NoBidiIsolation"
          : "Mf2DefaultBidiIsolation",
      inputs: (test.params ?? []).map(input),
      expected: test.exp,
      codes,
      parts: test.expParts?.map(partSignature),
    });
  }
}

const body = cases
  .map((test, index) => {
    const lines = [
      `  // ${test.label.replaceAll("\n", " ")}`,
      `  let result_${index} = format_mf2_with_provider(`,
      `    ${moonString(test.source)},`,
      `    mf2_fixture_context(`,
      `      ${moonString(test.locale)},`,
      `      [${test.inputs.join(", ")}],`,
      `      ${test.bidi},`,
      `    ),`,
      `    mf2_test_provider(),`,
      `  )`,
    ];
    if (test.expected !== undefined) {
      lines.push(`  assert_eq(result_${index}.value, ${moonString(test.expected)})`);
    }
    lines.push(
      `  assert_eq(result_${index}.errors.map(error => error.code), [${test.codes.join(", ")}])`,
    );
    if (test.parts) {
      lines.push(
        `  assert_eq(mf2_fixture_part_signatures(result_${index}.parts), [${test.parts.join(", ")}])`,
      );
    }
    return lines.join("\n");
  })
  .join("\n");

const source = `// Code generated by scripts/generate-mf2-format-tests.mjs; DO NOT EDIT.
// Unicode MessageFormat WG fixtures: ${pin}.

///|
test "Unicode MF2 pinned resolution formatting fixtures" {
${body}
}
`;

const target = new URL("runtime/mf2_upstream_format_wbtest.mbt", root);
const format = path => {
  const result = spawnSync("moon", ["fmt", path], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`moon fmt failed:\n${result.stdout}${result.stderr}`);
  }
};

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  const candidate = join(
    fileURLToPath(new URL("runtime/", root)),
    `.mf2-format-${process.pid}_wbtest.mbt`,
  );
  try {
    await writeFile(candidate, source);
    format(candidate);
    assert.equal(
      current,
      await readFile(candidate, "utf8"),
      "generated MF2 formatting tests are stale",
    );
  } finally {
    await rm(candidate, { force: true });
  }
  process.stdout.write(`MF2 generated formatting tests current: ${cases.length} cases\n`);
} else {
  await writeFile(target, source);
  format(fileURLToPath(target));
  process.stdout.write(`Generated MF2 formatting tests: ${cases.length} cases\n`);
}
