import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const pin = (
  await readFile(new URL("tests/unicode-mf2/PINNED_COMMIT", root), "utf8")
).trim();
assert.match(pin, /^[0-9a-f]{40}$/u);

const names = [
  "currency",
  "date",
  "datetime",
  "integer",
  "number",
  "offset",
  "percent",
  "string",
  "time",
];
const fixtures = await Promise.all(
  names.map(async name =>
    JSON.parse(
      await readFile(
        new URL(
          `tests/unicode-mf2/upstream/test/tests/functions/${name}.json`,
          root,
        ),
        "utf8",
      ),
    ),
  ),
);

const moonString = value => {
  let result = '"';
  for (const char of value) {
    const code = char.codePointAt(0);
    if (char === '"') result += '\\"';
    else if (char === "\\") result += "\\\\";
    else if (char === "\n") result += "\\n";
    else if (char === "\r") result += "\\r";
    else if (char === "\t") result += "\\t";
    else if (code < 0x20 || code === 0x7f) result += `\\u{${code.toString(16)}}`;
    else result += char;
  }
  return result + '"';
};
const doubleLiteral = value => (Number.isInteger(value) ? `${value}.0` : String(value));
const input = param => {
  const name = moonString(param.name);
  if (param.type === "datetime") {
    return `@runtime.Mf2Input::new(${name}, @runtime.TextValue(${moonString(param.value)}))`;
  }
  if (typeof param.value === "string") {
    return `@runtime.Mf2Input::new(${name}, @runtime.TextValue(${moonString(param.value)}))`;
  }
  if (typeof param.value === "number") {
    return `@runtime.Mf2Input::new(${name}, @runtime.DoubleValue(${doubleLiteral(param.value)}))`;
  }
  if (typeof param.value === "boolean") {
    return `@runtime.Mf2Input::new(${name}, @runtime.BoolValue(${param.value}))`;
  }
  throw new Error(`unsupported function fixture input: ${JSON.stringify(param)}`);
};

const errorCodes = new Map([
  ["syntax-error", "@runtime.Mf2SyntaxCode"],
  ["data-model-error", "@runtime.Mf2DataModelCode"],
  ["duplicate-variant", "@runtime.Mf2DuplicateVariantCode"],
  ["bad-operand", "@runtime.Mf2BadOperandCode"],
  ["bad-option", "@runtime.Mf2BadOptionCode"],
  ["bad-selector", "@runtime.Mf2BadSelectorCode"],
  ["bad-variant-key", "@runtime.Mf2BadVariantKeyCode"],
  ["unknown-function", "@runtime.Mf2UnknownFunctionCode"],
  ["unresolved-variable", "@runtime.Mf2UnresolvedVariableCode"],
]);

const cases = [];
for (let fileIndex = 0; fileIndex < fixtures.length; fileIndex += 1) {
  const fixture = fixtures[fileIndex];
  for (let index = 0; index < fixture.tests.length; index += 1) {
    const test = fixture.tests[index];
    const properties = { ...fixture.defaultTestProperties, ...test };
    const expectedErrors = properties.expErrors ?? [];
    const codes = expectedErrors.map(error => {
      assert.ok(errorCodes.has(error.type), `unmapped function error: ${error.type}`);
      return errorCodes.get(error.type);
    });
    const fields = [];
    for (const part of test.expParts ?? []) {
      if (part.type === "number") {
        for (const field of part.parts ?? []) {
          fields.push(`${field.type}|${field.value}`);
        }
      }
    }
    cases.push({
      label: `${names[fileIndex]} ${index}: ${test.description ?? fixture.scenario}`,
      source: test.src,
      expected: test.exp,
      locale: properties.locale ?? "en-US",
      inputs: (test.params ?? []).map(input),
      codes,
      fields: test.expParts ? fields : undefined,
    });
  }
}

const body = cases
  .map((test, index) => {
    const lines = [
      `  // ${test.label.replaceAll("\n", " ")}`,
      `  let context_${index} = match @runtime.Mf2FormattingContext::new(`,
      `    locale=${moonString(test.locale)},`,
      `    inputs=[${test.inputs.join(", ")}],`,
      `    time_zone="UTC",`,
      `    bidi_isolation=@runtime.Mf2NoBidiIsolation,`,
      `  ) {`,
      `    Ok(value) => value`,
      `    Err(error) => abort(error.message)`,
      `  }`,
      `  let result_${index} = format_mf2(${moonString(test.source)}, context_${index})`,
    ];
    if (test.expected !== undefined) {
      lines.push(`  assert_eq(result_${index}.value, ${moonString(test.expected)})`);
    }
    lines.push(
      `  assert_eq(result_${index}.errors.map(error => error.code), [${test.codes.join(", ")}])`,
    );
    if (test.fields) {
      lines.push(
        `  assert_eq(mf2_function_fixture_fields(result_${index}.parts), [${test.fields
          .map(moonString)
          .join(", ")}])`,
      );
    }
    return lines.join("\n");
  })
  .join("\n");

const source = `// Code generated by scripts/generate-mf2-function-tests.mjs; DO NOT EDIT.
// Unicode MessageFormat WG fixtures: ${pin}.

///|
fn mf2_function_fixture_fields(
  parts : Array[@runtime.Mf2FormattedPart],
) -> Array[String] {
  let fields : Array[String] = []
  for part in parts {
    match part {
      @runtime.Mf2FormattedExpressionPart(expression) =>
        for field in expression.fields {
          fields.push(field.kind + "|" + field.value)
        }
      _ => ()
    }
  }
  fields
}

///|
#cfg(target="js")
test "Unicode MF2 pinned default-function fixtures" {
${body}
}
`;

const target = new URL("runtime/js/mf2_upstream_functions_test.mbt", root);
const format = path => {
  const result = spawnSync("moon", ["fmt", path], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`moon fmt failed:\n${result.stdout}${result.stderr}`);
  }
};

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  const candidate = join(
    fileURLToPath(new URL("runtime/js/", root)),
    `.mf2-functions-${process.pid}_test.mbt`,
  );
  try {
    await writeFile(candidate, source);
    format(candidate);
    assert.equal(
      current,
      await readFile(candidate, "utf8"),
      "generated MF2 function tests are stale",
    );
  } finally {
    await rm(candidate, { force: true });
  }
  process.stdout.write(`MF2 generated function tests current: ${cases.length} cases\n`);
} else {
  await writeFile(target, source);
  format(fileURLToPath(target));
  process.stdout.write(`Generated MF2 function tests: ${cases.length} cases\n`);
}
