import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const registryUrl =
  "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry";
const expectedDate = "2026-08-08";
const expectedSha256 =
  "be21e91b6851f750a7b1a687f11209d46ad5a8471d6b10a1efc8d1dac4c8a926";
const vendoredPath = join(root, "tests/bcp47/language-subtag-registry");
const generatedPath = join(root, "runtime/bcp47_registry.generated.mbt");

const sha256 = value => createHash("sha256").update(value).digest("hex");

const parseRecords = source => {
  const records = [];
  for (const block of source.split(/\n%%\n/u)) {
    const fields = new Map();
    let previous;
    for (const line of block.split("\n")) {
      if (line.startsWith(" ") && previous) {
        const values = fields.get(previous);
        values[values.length - 1] += line.slice(1);
        continue;
      }
      const separator = line.indexOf(": ");
      if (separator < 1) continue;
      previous = line.slice(0, separator);
      const value = line.slice(separator + 2);
      const values = fields.get(previous) ?? [];
      values.push(value);
      fields.set(previous, values);
    }
    if (fields.has("Type")) records.push(fields);
  }
  return records;
};

const first = (record, name) => record.get(name)?.[0];
const entries = (records, type, key, predicate = () => true) =>
  records
    .filter(record => first(record, "Type") === type && predicate(record))
    .map(record => [first(record, key), first(record, "Preferred-Value")])
    .sort(([left], [right]) => left.localeCompare(right, "en"));

const moonString = value => JSON.stringify(value);
const optionMapFunction = (name, values, transformKey = value => value) => `///|
fn ${name}(value : String) -> String? {
  match value {
${values
  .map(
    ([key, preferred]) =>
      `    ${moonString(transformKey(key))} => Some(${moonString(preferred)})`,
  )
  .join("\n")}
    _ => None
  }
}`;

const stringMapFunction = (name, values, transformKey = value => value) => `///|
fn ${name}(value : String) -> String {
  match value {
${values
  .map(
    ([key, preferred]) =>
      `    ${moonString(transformKey(key))} => ${moonString(preferred)}`,
  )
  .join("\n")}
    _ => value
  }
}`;

const generate = source => {
  const records = parseRecords(source);
  const fileDate = /^File-Date: (\d{4}-\d{2}-\d{2})$/mu.exec(source)?.[1];
  assert.equal(fileDate, expectedDate);

  const wholePreferred = records
    .filter(
      record =>
        ["grandfathered", "redundant"].includes(first(record, "Type")) &&
        first(record, "Preferred-Value"),
    )
    .map(record => [first(record, "Tag"), first(record, "Preferred-Value")])
    .sort(([left], [right]) => left.localeCompare(right, "en"));
  const fixedGrandfathered = records
    .filter(
      record =>
        first(record, "Type") === "grandfathered" &&
        !first(record, "Preferred-Value"),
    )
    .map(record => [first(record, "Tag"), first(record, "Tag")])
    .sort(([left], [right]) => left.localeCompare(right, "en"));
  const languages = entries(
    records,
    "language",
    "Subtag",
    record => Boolean(first(record, "Preferred-Value")),
  );
  const scripts = entries(
    records,
    "script",
    "Subtag",
    record => Boolean(first(record, "Preferred-Value")),
  );
  const regions = entries(
    records,
    "region",
    "Subtag",
    record => Boolean(first(record, "Preferred-Value")),
  );
  const variants = entries(
    records,
    "variant",
    "Subtag",
    record => Boolean(first(record, "Preferred-Value")),
  );
  const extlangs = records
    .filter(record => first(record, "Type") === "extlang")
    .map(record => [
      first(record, "Subtag"),
      first(record, "Preferred-Value"),
      first(record, "Prefix"),
    ])
    .sort(([left], [right]) => left.localeCompare(right, "en"));

  return `// Code generated by scripts/sync-bcp47-registry.mjs; DO NOT EDIT.
// IANA Language Subtag Registry ${expectedDate}, SHA-256 ${expectedSha256}.

///|
/// Date of the IANA Language Subtag Registry snapshot used for BCP 47
/// canonicalization.
pub const BCP47_REGISTRY_DATE : String = ${moonString(expectedDate)}

///|
/// SHA-256 identity of the pinned IANA Language Subtag Registry snapshot.
pub const BCP47_REGISTRY_SHA256 : String = ${moonString(expectedSha256)}

${optionMapFunction("bcp47_preferred_whole_tag", wholePreferred, value => value.toLowerCase())}

${optionMapFunction("bcp47_fixed_grandfathered_tag", fixedGrandfathered, value => value.toLowerCase())}

${stringMapFunction("bcp47_preferred_language", languages, value => value.toLowerCase())}

${stringMapFunction("bcp47_preferred_script", scripts, value => value.toLowerCase())}

${stringMapFunction("bcp47_preferred_region", regions, value => value.toUpperCase())}

${stringMapFunction("bcp47_preferred_variant", variants, value => value.toLowerCase())}

${optionMapFunction(
  "bcp47_extlang_preferred",
  extlangs.map(([subtag, preferred]) => [subtag, preferred]),
  value => value.toLowerCase(),
)}

${optionMapFunction(
  "bcp47_extlang_prefix",
  extlangs.map(([subtag, , prefix]) => [subtag, prefix]),
  value => value.toLowerCase(),
)}
`;
};

const format = path => {
  const result = spawnSync("moon", ["fmt", path], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`moon fmt failed:\n${result.stdout}${result.stderr}`);
  }
};

const check = process.argv.includes("--check");
let content;
if (check) {
  content = await readFile(vendoredPath);
} else {
  const sourceArgument = process.argv.indexOf("--source-file");
  if (sourceArgument >= 0) {
    const sourceFile = process.argv[sourceArgument + 1];
    assert.ok(sourceFile, "--source-file requires a path");
    content = await readFile(sourceFile);
  } else {
    const response = await fetch(registryUrl);
    assert.ok(response.ok, `IANA registry download failed: ${response.status}`);
    content = Buffer.from(await response.arrayBuffer());
  }
}

assert.equal(sha256(content), expectedSha256, "unexpected IANA registry content");
const source = content.toString("utf8");
assert.match(source, new RegExp(`^File-Date: ${expectedDate}$`, "mu"));
const generated = generate(source);

if (check) {
  const candidate = join(dirname(generatedPath), `.bcp47-${process.pid}.generated.mbt`);
  try {
    await writeFile(candidate, generated);
    format(candidate);
    assert.equal(
      await readFile(generatedPath, "utf8"),
      await readFile(candidate, "utf8"),
      "generated BCP 47 registry source is stale",
    );
  } finally {
    await rm(candidate, { force: true });
  }
  process.stdout.write(
    `BCP 47 registry current: ${expectedDate} (${expectedSha256})\n`,
  );
} else {
  await mkdir(dirname(vendoredPath), { recursive: true });
  await writeFile(vendoredPath, content);
  await writeFile(generatedPath, generated);
  format(generatedPath);
  process.stdout.write(
    `Synchronized BCP 47 registry ${expectedDate} (${expectedSha256})\n`,
  );
}
